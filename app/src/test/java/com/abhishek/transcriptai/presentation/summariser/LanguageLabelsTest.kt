package com.abhishek.transcriptai.presentation.summariser

import com.abhishek.transcriptai.domain.model.CaptionTrack
import com.abhishek.transcriptai.domain.model.SubtitleResult
import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertNull
import org.junit.Assert.assertTrue
import org.junit.Test

class LanguageLabelsTest {

    @Test
    fun captionLabel_usesTheNativeNameWhenTheCatalogKnowsTheLanguage() {
        assertEquals("Bahasa Indonesia", captionLabel("id", "Indonesian", isAutoGenerated = false))
        assertEquals("English (auto-generated)", captionLabel("en", "English (auto-generated)", isAutoGenerated = true))
        assertEquals("עברית", captionLabel("iw", "Hebrew", isAutoGenerated = false))
    }

    @Test
    fun captionLabel_keepsTheCatalogNameAndAddsTheRegionOfARegionalCode() {
        assertEquals("Português (Brasil)", captionLabel("pt-BR", "Portuguese (Brazil)", isAutoGenerated = false))
        assertEquals("Español (Latinoamérica)", captionLabel("es-419", "Spanish (Latin America)", isAutoGenerated = false))
        assertEquals("Français (Canada)", captionLabel("fr-CA", "French (Canada)", isAutoGenerated = false))
        assertEquals("繁體中文", captionLabel("zh-Hant", "Chinese (Traditional)", isAutoGenerated = false))
        assertEquals("简体中文", captionLabel("zh-Hans", "Chinese (Simplified)", isAutoGenerated = false))
    }

    @Test
    fun captionLabel_namesLanguagesTheCatalogLacksInTheirOwnScript() {
        assertEquals("Հայերեն", captionLabel("hy", "Armenian", isAutoGenerated = false))
        assertEquals("Български", captionLabel("bg", "Bulgarian", isAutoGenerated = false))
        assertEquals("မြန်မာ", captionLabel("my", "Burmese", isAutoGenerated = false))
        assertEquals("Català", captionLabel("ca", "Catalan", isAutoGenerated = false))
        assertEquals("Hrvatski", captionLabel("hr", "Croatian", isAutoGenerated = false))
        assertEquals("Հայերեն (auto-generated)", captionLabel("hy", "Armenian (auto-generated)", isAutoGenerated = true))
    }

    @Test
    fun captionLabel_acceptsLegacyAndUnderscoreCodes() {
        assertEquals("Jawa", captionLabel("jw", "Javanese", isAutoGenerated = false))
        assertEquals("Română", captionLabel("mo", "Moldavian", isAutoGenerated = false))
        assertEquals("עברית (ישראל)", captionLabel("iw-IL", "Hebrew (Israel)", isAutoGenerated = false))
        assertEquals("Português (Brasil)", captionLabel("pt_BR", "Portuguese (Brazil)", isAutoGenerated = false))
    }

    @Test
    fun captionLabel_namesAScriptVariantAfterLocaleRatherThanTheCatalogsOtherScript() {
        assertEquals("Srpski (latinica)", captionLabel("sr-Latn", "Serbian (Latin)", isAutoGenerated = false))
    }

    @Test
    fun captionLabel_usesTheTrackNameWhenNoLanguageIsKnownForTheCode() {
        assertEquals("Made-up language", captionLabel("zzz", "Made-up language", isAutoGenerated = false))
        assertEquals("Made-up language", captionLabel("zz-ZZ", "Made-up language (auto-generated)", isAutoGenerated = false))
        assertEquals("Made-up language (auto-generated)", captionLabel("zzz", "Made-up language (auto-generated)", isAutoGenerated = true))
        assertEquals("zzz", captionLabel("zzz", null, isAutoGenerated = false))
        assertEquals("zzz", captionLabel("zzz", " ", isAutoGenerated = false))
        assertNull(captionLabel(null, null, isAutoGenerated = false))
        assertNull(captionLabel("", "", isAutoGenerated = false))
    }

    @Test
    fun nativeLanguageName_isNullForCodesThatNameNoLanguage() {
        assertNull(nativeLanguageName(null))
        assertNull(nativeLanguageName(""))
        assertNull(nativeLanguageName("zzz"))
        assertNull(nativeLanguageName("und"))
    }

    @Test
    fun secondaryLabel_showsYouTubesNameOnlyWhenItAddsInformation() {
        assertEquals("Indonesian", CaptionTrack("id", "Indonesian", false).secondaryLabel())
        assertNull(CaptionTrack("en", "English", false).secondaryLabel())
        assertNull(CaptionTrack("en", "English (auto-generated)", true).secondaryLabel())
        assertEquals("Spanish (Latin America)", CaptionTrack("es-419", "Spanish (Latin America)", false).secondaryLabel())
        assertEquals("Armenian", CaptionTrack("hy", "Armenian", false).secondaryLabel())
        assertEquals("Armenian", CaptionTrack("hy", "Armenian (auto-generated)", true).secondaryLabel())
        assertNull(CaptionTrack("zzz", "Made-up language", false).secondaryLabel())
    }

    @Test
    fun languageRows_labelEachTrackAndMarkTheOneShowing() {
        val current = SubtitleResult(text = "t", videoId = "v", languageCode = "hy", isAutoGenerated = false)
        val tracks = listOf(
            CaptionTrack("en", "English", false),
            CaptionTrack("hy", "Armenian", false)
        )

        val rows = languageRows(tracks, current)

        assertEquals(listOf("English", "Հայերեն"), rows.map { it.label })
        assertEquals(listOf(null, "Armenian"), rows.map { it.secondary })
        assertEquals(listOf(false, true), rows.map { it.isCurrent })
        assertEquals(tracks, rows.map { it.track })
    }

    @Test
    fun languageRows_giveEveryRowAUniqueKeyEvenForTracksThatLookAlike() {
        val current = SubtitleResult(text = "t", videoId = "v")
        val tracks = listOf(
            CaptionTrack("en", "English", false),
            CaptionTrack("en", "English - CC", false),
            CaptionTrack("en", "English (auto-generated)", true),
            CaptionTrack("en", "English - CC 2", false)
        )

        val keys = languageRows(tracks, current).map { it.key }

        assertEquals(tracks.size, keys.toSet().size)
        assertEquals("en|false", keys[0])
    }

    @Test
    fun isShowing_matchesCodeAndAutoGeneratedFlag() {
        val result = SubtitleResult(text = "t", videoId = "v", languageCode = "en", isAutoGenerated = true)

        assertTrue(result.isShowing(CaptionTrack("en", "English (auto-generated)", true)))
        assertFalse(result.isShowing(CaptionTrack("en", "English", false)))
        assertFalse(result.isShowing(CaptionTrack("id", "Indonesian", true)))
        assertFalse(SubtitleResult(text = "t", videoId = "v").isShowing(CaptionTrack("en", "English", false)))
    }

    @Test
    fun requestPreferences_asksForTheAutoKeywordOnlyForTheAutoGeneratedTrack() {
        assertEquals(listOf("auto"), CaptionTrack("en", "English (auto-generated)", true).requestPreferences())
        assertEquals(listOf("id"), CaptionTrack("id", "Indonesian", false).requestPreferences())
    }

    @Test
    fun languageUnavailableNotice_namesTheRequestedAndTheShownLanguage() {
        val shown = SubtitleResult(text = "t", videoId = "v", languageCode = "en", languageName = "English")
        val shownAuto = shown.copy(languageName = "English (auto-generated)", isAutoGenerated = true)

        assertEquals(
            "Indonesian isn't available for this video. Showing English.",
            languageUnavailableNotice("Indonesian", shown)
        )
        assertEquals(
            "Auto-generated captions aren't available for this video. Showing English.",
            languageUnavailableNotice(null, shown)
        )
        assertEquals(
            "Indonesian isn't available for this video. Showing English (auto-generated).",
            languageUnavailableNotice("Indonesian", shownAuto)
        )
        assertEquals(
            "Indonesian isn't available for this video.",
            languageUnavailableNotice("Indonesian", SubtitleResult(text = "t", videoId = "v"))
        )
    }

    @Test
    fun youTubeWatchUrl_pointsAtTheWatchPage() {
        assertEquals("https://www.youtube.com/watch?v=dQw4w9WgXcQ", youTubeWatchUrl("dQw4w9WgXcQ"))
    }

    @Test
    fun youTubeWatchUrl_keepsIdCharactersThatAreSafeInALink() {
        assertEquals("https://www.youtube.com/watch?v=a-B_c1", youTubeWatchUrl("a-B_c1"))
        assertEquals("https://www.youtube.com/watch?v=a%26b", youTubeWatchUrl("a&b"))
    }
}
