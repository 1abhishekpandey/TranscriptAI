package com.abhishek.transcriptai.presentation.summariser

import com.abhishek.transcriptai.domain.model.CaptionTrack
import com.abhishek.transcriptai.domain.model.LanguageChoice
import com.abhishek.transcriptai.domain.model.LanguageMode
import com.abhishek.transcriptai.domain.model.SubtitleLanguage
import com.abhishek.transcriptai.domain.model.SubtitleLanguages
import com.abhishek.transcriptai.domain.model.SubtitleResult
import java.net.URLEncoder
import java.util.Locale

private const val AUTO_GENERATED_SUFFIX = " (auto-generated)"

/** Language codes YouTube still uses that Java's [Locale] knows only under the current code. */
private val LegacyLanguageCodes = mapOf(
    "iw" to "he",
    "in" to "id",
    "ji" to "yi",
    "jw" to "jv",
    "mo" to "ro"
)
private val AutoGeneratedSuffixRegex = Regex("""\s*\(\s*auto-generated\s*\)\s*$""", RegexOption.IGNORE_CASE)

/**
 * Finds the catalog language for a YouTube caption code.
 * Tries the full code first (e.g., "zh-Hant"), then the part before the first "-" (e.g., "pt" for "pt-BR").
 *
 * @param code YouTube caption code
 * @return The matching catalog entry, or null when the catalog doesn't know the language
 */
internal fun findCatalogLanguage(code: String?): SubtitleLanguage? {
    if (code.isNullOrBlank()) return null
    val base = code.substringBefore('-')
    return SubtitleLanguages.all.firstOrNull { language ->
        language.codes.any { it.equals(code, ignoreCase = true) }
    } ?: SubtitleLanguages.all.firstOrNull { language ->
        language.codes.any { it.equals(base, ignoreCase = true) }
    }
}

/**
 * Removes a trailing "(auto-generated)" marker that YouTube puts in some track names.
 */
private fun stripAutoGeneratedSuffix(name: String): String =
    name.replace(AutoGeneratedSuffixRegex, "").trim()

/**
 * The [Locale] for a YouTube caption code, with legacy language codes ("iw", "in", ...) and
 * underscores ("zh_Hans") accepted.
 *
 * @return The locale, or null when the code doesn't name a language
 */
private fun localeForCode(code: String): Locale? {
    val parts = code.trim().replace('_', '-').split('-')
    val language = parts.first().lowercase()
    val tag = (listOf(LegacyLanguageCodes[language] ?: language) + parts.drop(1)).joinToString("-")
    return Locale.forLanguageTag(tag).takeIf { it.language.isNotEmpty() }
}

/** Upper-cases the first letter by the rules of [locale], e.g. "español" becomes "Español". */
private fun String.capitalizeFor(locale: Locale): String =
    replaceFirstChar { if (it.isLowerCase()) it.titlecase(locale) else it.toString() }

/**
 * The region or script a caption code adds to its language, written in that language
 * (e.g., "Brasil" for "pt-BR"), or null when the code is a plain language or the name is unknown.
 */
private fun Locale.nativeQualifier(): String? {
    val regionName = getDisplayCountry(this).takeIf { it.isNotBlank() && !it.equals(country, ignoreCase = true) }
    val scriptName = getDisplayScript(this).takeIf { it.isNotBlank() && !it.equals(script, ignoreCase = true) }
    return regionName ?: scriptName
}

/**
 * Name of a language written in that language, for any caption code YouTube uses.
 *
 * The app's catalog wins where it knows the language, so the names match the language settings page.
 * Any other language is named by [Locale], which knows hundreds of them (e.g., "Հայերեն", "Български").
 * A regional code adds its region to the name ("Português (Brasil)", "Español (Latinoamérica)").
 *
 * @param code YouTube caption code, e.g. "hy", "iw", "es-419" or "zh-Hant"
 * @return The name, or null when neither the catalog nor [Locale] knows the language
 */
internal fun nativeLanguageName(code: String?): String? {
    if (code.isNullOrBlank()) return null

    SubtitleLanguages.all.firstOrNull { language ->
        language.codes.any { it.equals(code, ignoreCase = true) }
    }?.let { return it.nativeName }

    val locale = localeForCode(code) ?: return null

    // A script ("sr-Latn") changes how the language is written, so the catalog's name may use the wrong one
    if (locale.script.isEmpty()) {
        findCatalogLanguage(code)?.let { language ->
            val qualifier = locale.nativeQualifier()
            return if (qualifier != null) "${language.nativeName} ($qualifier)" else language.nativeName
        }
    }

    // Locale returns the code itself for a language it has no name for
    val languageName = locale.getDisplayLanguage(locale)
    if (languageName.isBlank() || languageName.equals(locale.language, ignoreCase = true)) return null
    return locale.getDisplayName(locale).capitalizeFor(locale)
}

/**
 * Name shown for a caption track in the app's own UI.
 * Uses the language's own name when the catalog or [Locale] knows it, otherwise the name YouTube gave the track.
 *
 * @param code Caption code of the track
 * @param name Name YouTube gave the track
 * @param isAutoGenerated Whether YouTube generated the track from the speech
 * @return e.g. "Bahasa Indonesia" or "English (auto-generated)", or null when nothing identifies the track
 */
internal fun captionLabel(code: String?, name: String?, isAutoGenerated: Boolean): String? {
    val base = nativeLanguageName(code)
        ?: name?.let(::stripAutoGeneratedSuffix)?.takeIf { it.isNotBlank() }
        ?: code?.takeIf { it.isNotBlank() }
        ?: return null
    return if (isAutoGenerated) base + AUTO_GENERATED_SUFFIX else base
}

/** Label of the track this result was downloaded from, or null when the result doesn't say. */
internal fun SubtitleResult.trackLabel(): String? =
    captionLabel(languageCode, languageName, isAutoGenerated)

/** Label of a caption track the video offers. */
internal fun CaptionTrack.label(): String =
    captionLabel(languageCode, name, isAutoGenerated) ?: languageCode

/**
 * The name YouTube gave the track, shown under [label] so tracks that share a native name
 * (e.g., two regional variants of one language) can be told apart.
 * Null when it would only repeat the label.
 */
internal fun CaptionTrack.secondaryLabel(): String? {
    val englishName = stripAutoGeneratedSuffix(name)
    if (englishName.isBlank()) return null
    val base = label().let { if (isAutoGenerated) it.removeSuffix(AUTO_GENERATED_SUFFIX) else it }
    return englishName.takeUnless { it.equals(base, ignoreCase = true) }
}

/**
 * One row of the language sheet, worked out once so scrolling the list does no naming work.
 *
 * @property key Identifies the row in the list; unique even when the video lists two tracks alike
 * @property track The caption track the row stands for
 * @property label Name of the language in its own script
 * @property secondary YouTube's name for the track, when it adds information
 * @property isCurrent Whether the transcript on screen came from this track
 */
internal data class LanguageRow(
    val key: String,
    val track: CaptionTrack,
    val label: String,
    val secondary: String?,
    val isCurrent: Boolean
)

/**
 * Rows for the language sheet, in the order YouTube lists the tracks.
 * A list needs a unique key per row, and a video can list two tracks with the same code, so a repeat gets a number.
 */
internal fun languageRows(tracks: List<CaptionTrack>, current: SubtitleResult): List<LanguageRow> {
    val timesSeen = HashMap<String, Int>()
    return tracks.map { track ->
        val baseKey = "${track.languageCode}|${track.isAutoGenerated}"
        val seen = timesSeen.merge(baseKey, 1, Int::plus) ?: 1
        LanguageRow(
            key = if (seen == 1) baseKey else "$baseKey#$seen",
            track = track,
            label = track.label(),
            secondary = track.secondaryLabel(),
            isCurrent = current.isShowing(track)
        )
    }
}

/** Whether this result was downloaded from the given track. */
internal fun SubtitleResult.isShowing(track: CaptionTrack): Boolean {
    val code = languageCode ?: return false
    return track.languageCode.equals(code, ignoreCase = true) && track.isAutoGenerated == isAutoGenerated
}

/**
 * Language codes to ask the downloader for so it returns exactly this track.
 * The auto-generated track is requested with the "auto" keyword rather than a code.
 */
internal fun CaptionTrack.requestPreferences(): List<String> =
    if (isAutoGenerated) listOf("auto") else listOf(languageCode)

/** English name of the language the user asked for, or null when they asked for auto-generated captions. */
internal fun LanguageChoice.requestedLanguageName(): String? =
    if (mode == LanguageMode.OTHER) otherLanguage?.englishName else null

/**
 * Message explaining that the requested language doesn't exist for the video.
 *
 * @param requestedLanguage English name of the language that was requested, or null for auto-generated captions
 * @param shown The result that was downloaded instead
 */
internal fun languageUnavailableNotice(requestedLanguage: String?, shown: SubtitleResult): String {
    val unavailable = if (requestedLanguage == null) {
        "Auto-generated captions aren't available"
    } else {
        "$requestedLanguage isn't available"
    }
    val shownName = shown.languageName?.let(::stripAutoGeneratedSuffix)?.takeIf { it.isNotBlank() }
        ?: findCatalogLanguage(shown.languageCode)?.englishName
        ?: shown.languageCode?.takeIf { it.isNotBlank() }
    val showing = shownName?.let { if (shown.isAutoGenerated) it + AUTO_GENERATED_SUFFIX else it }
    return if (showing != null) {
        "$unavailable for this video. Showing $showing."
    } else {
        "$unavailable for this video."
    }
}

/** Link that opens the video on YouTube. */
internal fun youTubeWatchUrl(videoId: String): String =
    "https://www.youtube.com/watch?v=" + URLEncoder.encode(videoId, "UTF-8")
