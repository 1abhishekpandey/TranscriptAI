/** Space under the last line so the Share button doesn't cover it. */
private val BottomClearance = 96.dp

/** Space on each side of the page's content. */
private val SideGutter = 16.dp

/** Items before the transcript's own: the header, the AI prompt card and the pinned toolbar. */
private const val FIXED_LEADING_ITEM_COUNT = 3

/**
 * The loaded page: header, banner, AI prompt card and the transcript, all in one list so the whole
 * page scrolls together and the transcript can use the full screen height.
 *
 * Only the toolbar (word count, Search, Copy, and the search field) stays pinned at the top while the
 * transcript scrolls under it. Search highlights the matches and scrolls the one in focus into view.
 *
 * @param uiState State of the screen
 * @param subtitle The transcript on screen
 * @param isSearchActive Whether the search field is open
 * @param onSearchActiveChange Callback to open or close the search
 * @param onEvent Callback for the user's actions
 * @param modifier Optional modifier for customization
 */
@OptIn(ExperimentalFoundationApi::class)
@Composable
internal fun TranscriptContent(
    uiState: SummariserUiState,
    subtitle: SubtitleResult,
    isSearchActive: Boolean,
    onSearchActiveChange: (Boolean) -> Unit,
    onEvent: (SummariserUiEvent) -> Unit,
    modifier: Modifier = Modifier
) {
    val text = subtitle.text
    val paragraphs = remember(text) { splitIntoParagraphs(text) }
    val paragraphTexts = remember(paragraphs) { paragraphs.map { it.textIn(text) } }
    val wordCountText = remember(text) { formatWordCount(countWords(text)) }
    val languageLabel = remember(subtitle.languageCode, subtitle.languageName, subtitle.isAutoGenerated) {
        subtitle.trackLabel()
    }

    var query by rememberSaveable { mutableStateOf("") }
    var currentMatch by rememberSaveable(query) { mutableStateOf(0) }
    LaunchedEffect(isSearchActive) {
        if (!isSearchActive) query = ""
    }

    val activeQuery = if (isSearchActive) query else ""
    val matchStarts = remember(text, activeQuery) { findMatchStarts(text, activeQuery) }
    val selectedMatch = if (matchStarts.isEmpty()) -1 else currentMatch.coerceIn(0, matchStarts.lastIndex)

    val statusText = when {
        activeQuery.isBlank() -> wordCountText
        matchStarts.isEmpty() -> "No matches"
        else -> "${selectedMatch + 1} of ${matchStarts.size}"
    }

    val readingStyle = MaterialTheme.typography.bodyLarge.copy(
        fontSize = 16.sp,
        lineHeight = 26.sp,
        letterSpacing = 0.2.sp
    )
    val colors = MaterialTheme.colorScheme
    val highlight = remember(colors.tertiaryContainer, colors.onTertiaryContainer, colors.primary, colors.onPrimary) {
        MatchHighlight(
            match = SpanStyle(background = colors.tertiaryContainer, color = colors.onTertiaryContainer),
            selected = SpanStyle(background = colors.primary, color = colors.onPrimary)
        )
    }

    val hasNotice = uiState.languageNotice != null
    val toolbarIndex = FIXED_LEADING_ITEM_COUNT - 1 + if (hasNotice) 1 else 0
    val firstParagraphIndex = toolbarIndex + 1

    val listState = rememberLazyListState()
    val scope = rememberCoroutineScope()
    var toolbarHeightPx by remember { mutableIntStateOf(0) }

    // The pinned toolbar covers the top of the list, so a match is scrolled to just below it
    LaunchedEffect(matchStarts, selectedMatch) {
        if (selectedMatch >= 0) {
            val paragraphIndex = paragraphIndexAt(paragraphs, matchStarts[selectedMatch])
            listState.animateScrollToItem(firstParagraphIndex + paragraphIndex, scrollOffset = -toolbarHeightPx)
        }
    }

    fun stepMatch(step: Int) {
        if (matchStarts.isNotEmpty()) {
            currentMatch = (selectedMatch + step + matchStarts.size) % matchStarts.size
        }
    }

    LazyColumn(
        state = listState,
        modifier = modifier.fillMaxSize(),
        contentPadding = PaddingValues(bottom = BottomClearance)
    ) {
        item(key = "header", contentType = "header") {
            VideoHeader(
                title = subtitle.videoTitle?.takeIf { it.isNotBlank() } ?: subtitle.videoId,
                languageLabel = languageLabel,
                canChangeLanguage = subtitle.availableTracks.size > 1,
                isLanguageBusy = uiState.isSwitchingLanguage,
                onLanguageClick = { onEvent(SummariserUiEvent.LanguageChipClicked) },
                modifier = Modifier.padding(start = SideGutter, end = SideGutter, top = 4.dp, bottom = 12.dp)
            )
        }

        uiState.languageNotice?.let { notice ->
            item(key = "notice", contentType = "notice") {
                LanguageNoticeBanner(
                    message = notice,
                    onDismiss = { onEvent(SummariserUiEvent.DismissLanguageNotice) },
                    modifier = Modifier.padding(start = SideGutter, end = SideGutter, bottom = 12.dp)
                )
            }
        }

        item(key = "aiPrompt", contentType = "aiPrompt") {
            AiPromptCard(
                isEnabled = uiState.isAiSummariserEnabled,
                prompts = uiState.prompts,
                selectedPrompt = uiState.selectedPrompt,
                onToggle = { onEvent(SummariserUiEvent.ToggleAiSummariser(it)) },
                onSelectPrompt = { onEvent(SummariserUiEvent.SelectPrompt(it)) },
                onEditClick = { onEvent(SummariserUiEvent.NavigateToPromptEditor) },
                modifier = Modifier.padding(start = SideGutter, end = SideGutter, bottom = 12.dp)
            )
        }

        // Nothing to search or copy while another language is loading, so the toolbar waits for it
        if (!uiState.isSwitchingLanguage) {
            stickyHeader(key = "toolbar", contentType = "toolbar") {
                TranscriptToolbar(
                    statusText = statusText,
                    isSearchActive = isSearchActive,
                    query = query,
                    canStepMatches = matchStarts.size > 1,
                    onQueryChange = { query = it },
                    onSearchSubmit = { stepMatch(1) },
                    onSearchClick = {
                        onSearchActiveChange(true)
                        // Bring the toolbar to the top so the matches get the screen; one already pinned stays put
                        if (listState.firstVisibleItemIndex < toolbarIndex) {
                            scope.launch { listState.animateScrollToItem(toolbarIndex) }
                        }
                    },
                    onCopyClick = { onEvent(SummariserUiEvent.CopyTranscriptClicked) },
                    onPreviousMatch = { stepMatch(-1) },
                    onNextMatch = { stepMatch(1) },
                    onCloseSearch = { onSearchActiveChange(false) },
                    modifier = Modifier.onSizeChanged { toolbarHeightPx = it.height }
                )
            }
        }

        when {
            uiState.isSwitchingLanguage -> item(key = "loading", contentType = "loading") {
                TranscriptLoadingCard(
                    languageLabel = uiState.switchingLanguageLabel,
                    modifier = Modifier
                        .padding(start = SideGutter, end = SideGutter, top = 14.dp)
                        .height(240.dp)
                )
            }

            paragraphs.isEmpty() -> item(key = "empty", contentType = "empty") {
                Box(
                    modifier = Modifier
                        .fillMaxWidth()
                        .padding(24.dp),
                    contentAlignment = Alignment.Center
                ) {
                    Text(
                        text = "This transcript is empty.",
                        style = MaterialTheme.typography.bodyMedium,
                        color = MaterialTheme.colorScheme.onSurfaceVariant
                    )
                }
            }

            else -> items(
                count = paragraphs.size,
                key = { paragraphs[it].start },
                contentType = { "paragraph" }
            ) { index ->
                ParagraphText(
                    text = paragraphTexts[index],
                    paragraph = paragraphs[index],
                    matchStarts = matchStarts,
                    queryLength = activeQuery.length,
                    selectedMatch = selectedMatch,
                    style = readingStyle,
                    highlight = highlight,
                    modifier = Modifier.padding(
                        start = SideGutter,
                        end = SideGutter,
                        top = if (index == 0) 14.dp else 7.dp,
                        bottom = 7.dp
                    )
                )
            }
        }
    }
}

private fun formatWordCount(count: Int): String =
    if (count == 1) "1 word" else "${NumberFormat.getIntegerInstance().format(count)} words"
